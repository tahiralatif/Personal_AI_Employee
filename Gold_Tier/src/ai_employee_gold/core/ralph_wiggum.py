from agents import function_tool

# Global loop instance
ralph_wiggum_loop = RalphWiggumLoop(max_iterations=10, check_interval=5)


@function_tool()
def ensure_task_completion(
    task_description: str,
    max_iterations: int = 10,
    domain: str = "business"
) -> str:
    """
    Ensure a task completes using Ralph Wiggum loop.
    
    This skill keeps the agent working until the task is fully complete.
    
    Args:
        task_description: Description of task to complete
        max_iterations: Maximum iterations before giving up
        domain: Task domain (business, personal, finance)
    
    Returns:
        Task completion status
    """
    # Create task
    task_id = ralph_wiggum_loop.create_task(
        prompt=task_description,
        domain=domain,
        max_iterations=max_iterations
    )
    
    return (
        f"Task created: {task_id}\n"
        f"Max iterations: {max_iterations}\n"
        f"Domain: {domain}\n\n"
        f"The agent will continue working on this task until complete "
        f"or max iterations ({max_iterations}) is reached."
    )


@function_tool()
def check_task_status(task_id: str) -> str:
    """
    Check status of a task.
    
    Args:
        task_id: Task ID to check
    
    Returns:
        Task status information
    """
    state = ralph_wiggum_loop.get_task_state(task_id)
    
    if not state:
        return f"Task not found: {task_id}"
    
    return (
        f"Task: {state.task_id}\n"
        f"Status: {state.status.value.upper()}\n"
        f"Progress: {state.progress}%\n"
        f"Step: {state.current_step}/{state.total_steps}\n"
        f"Iteration: {state.current_iteration}/{state.max_iterations}\n"
        f"Last Output: {state.last_output or 'None'}\n"
        f"Error: {state.error_message or 'None'}"
    )


@function_tool()
def update_task_progress(
    task_id: str,
    progress: int,
    current_step: int,
    output: str
) -> str:
    """
    Update task progress.
    
    Args:
        task_id: Task ID
        progress: Progress percentage (0-100)
        current_step: Current step number
        output: Current output from agent
    
    Returns:
        Confirmation of update
    """
    ralph_wiggum_loop.update_progress(task_id, progress, current_step, output)
    return f"Updated task {task_id}: {progress}% complete, step {current_step}"


@function_tool()
def mark_task_complete(task_id: str, final_output: str) -> str:
    """
    Mark task as complete.
    
    Args:
        task_id: Task ID
        final_output: Final output
    
    Returns:
        Confirmation
    """
    ralph_wiggum_loop.mark_complete(task_id, final_output)
    return f"Task {task_id} marked as complete"


@function_tool()
def get_active_tasks() -> str:
    """
    Get list of active tasks.
    
    Returns:
        List of active tasks
    """
    active = [
        task for task in ralph_wiggum_loop.active_tasks.values()
        if task.status in [TaskStatus.PENDING, TaskStatus.IN_PROGRESS]
    ]
    
    if not active:
        return "No active tasks"
    
    result = "Active Tasks:\n\n"
    for task in active:
        result += (
            f"- {task.task_id}: {task.progress}% complete, "
            f"step {task.current_step}/{task.total_steps}\n"
        )
    
    return result


